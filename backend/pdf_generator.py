import io
from typing import Any

from fpdf import FPDF
from fastapi.responses import StreamingResponse

try:
    from backend.utils import risk_guidance
except ImportError:  # pragma: no cover
    from utils import risk_guidance


def generate_pdf_report(record: dict[str, Any]) -> StreamingResponse:
    """Generate professional medical-style PDF report."""
    top_predictions = record["top_predictions"]

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()


    pdf.set_font("Arial", "B", 18)
    pdf.cell(0, 12, "AI HEALTH DIAGNOSTIC REPORT", ln=True, align="C")

    pdf.set_draw_color(0, 0, 0)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(5)

    pdf.set_font("Arial", "", 10)
    pdf.cell(95, 8, f"Report ID: {record['id']}")
    pdf.cell(95, 8, f"Date: {record['created_at']}", ln=True)

    pdf.ln(4)

    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "PATIENT INFORMATION", ln=True)

    start_y = pdf.get_y()

    pdf.rect(10, start_y, 190, 28)

    pdf.set_xy(14, start_y + 3)

    pdf.set_font("Arial", "", 11)

    pdf.cell(90, 7, f"Name: {record['name']}")
    pdf.cell(90, 7, f"Age: {record['age']}", ln=True)

    pdf.cell(90, 7, f"Father Name: {record['fname']}")
    pdf.cell(90, 7, f"Gender: {record['gender']}", ln=True)

    pdf.set_x(14)

    if record.get("basic_info"):
        basic_info = str(record["basic_info"])[:120]
        pdf.multi_cell(180, 6, f"Additional Info: {basic_info}")

    pdf.set_y(start_y + 32)


    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "CLINICAL SUMMARY", ln=True)

    pdf.set_fill_color(235, 245, 255)

    pdf.set_font("Arial", "B", 12)
    pdf.cell(
        0,
        10,
        f"Predicted Disease: {record['predicted_disease']}",
        ln=True,
        fill=True,
    )

    pdf.set_font("Arial", "", 11)
    pdf.cell(0, 8, f"Risk Level: {record['risk_level']}", ln=True)

    pdf.cell(
        0,
        8,
        f"Confidence Score: {record['confidence'] * 100:.2f}%",
        ln=True,
    )

    pdf.multi_cell(
        0,
        7,
        f"Recommendation: {risk_guidance(record['risk_level'])}",
    )

    pdf.ln(2)

    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "REPORTED SYMPTOMS", ln=True)

    pdf.set_font("Arial", "", 11)

    for symptom in record["symptoms"]:
        pdf.cell(5)
        pdf.cell(0, 7, f"- {symptom}", ln=True)

    pdf.ln(3)


    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "TOP PREDICTIONS", ln=True)

    pdf.set_fill_color(220, 220, 220)

    pdf.set_font("Arial", "B", 11)

    pdf.cell(130, 10, "Disease", border=1, fill=True)
    pdf.cell(50, 10, "Probability", border=1, fill=True, ln=True)

    pdf.set_font("Arial", "", 11)

    for item in top_predictions:
        pdf.cell(130, 10, str(item["disease"]), border=1)
        pdf.cell(
            50,
            10,
            f"{item['percent']:.2f}%",
            border=1,
            ln=True,
        )

    pdf.ln(5)

    pdf.set_font("Arial", "I", 9)

    pdf.multi_cell(
        0,
        5,
        "DISCLAIMER: This report is generated by an AI-based "
        "prediction system and is intended for informational "
        "purposes only. It should not be used as a substitute "
        "for professional medical advice, diagnosis, or treatment."

    )


    pdf.ln(3)
    pdf.set_font("Arial", "I", 8)
    pdf.cell(
        0,
        5,
        "Generated by AI Health Diagnostic System"
        " :SHOUKAT ALI",
        align="C",
    )

    rendered = pdf.output(dest="S")

    if isinstance(rendered, (bytes, bytearray)):
        content = bytes(rendered)
    else:
        content = str(rendered).encode("latin-1")

    filename = f"prediction_report_{record['id']}.pdf"

    return StreamingResponse(
        io.BytesIO(content),
        media_type="application/pdf",
        headers={
            "Content-Disposition":
            f'attachment; filename="{filename}"'
        },
    )
